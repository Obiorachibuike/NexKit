/**
 * Code templates. Pure functions returning file contents so they can be unit
 * tested and reused programmatically.
 */

export type Framework = "express" | "fastify" | "none";

export interface EnvFieldSpec {
  key: string;
  type: "string" | "number" | "port" | "boolean" | "url" | "enum" | "list";
  default?: string | number | boolean | string[];
  values?: string[];
  optional?: boolean;
  description?: string;
}

/** Default schema used by `nexkit init` and `nexkit generate config` without a source file. */
export const DEFAULT_ENV_FIELDS: EnvFieldSpec[] = [
  {
    key: "NODE_ENV",
    type: "enum",
    values: ["development", "test", "production"],
    default: "development",
    description: "Runtime environment",
  },
  { key: "PORT", type: "port", default: 3000, description: "HTTP port to listen on" },
  {
    key: "LOG_LEVEL",
    type: "enum",
    values: ["trace", "debug", "info", "warn", "error", "fatal", "silent"],
    default: "info",
    description: "Minimum log level",
  },
  {
    key: "DATABASE_URL",
    type: "url",
    description: "Primary database connection string",
    optional: true,
  },
];

const SECRET_KEY =
  /(PASS(WORD)?|SECRET|TOKEN|PRIVATE|CREDENTIAL|API_?KEY|ACCESS_?KEY|_KEY$|DSN|DATABASE_URL|REDIS_URL|MONGO(DB)?_URI|CONNECTION_STRING)/i;

/**
 * Infers an env schema from `.env`-style content (`KEY=value` lines).
 * Secret-looking keys never receive defaults.
 */
export function inferEnvFields(dotenv: string): EnvFieldSpec[] {
  const fields: EnvFieldSpec[] = [];
  let pendingComment: string | undefined;
  let pendingMeta: Partial<EnvFieldSpec> | undefined;

  const push = (key: string, value: string, commentedOut: boolean) => {
    let field: EnvFieldSpec;
    if (pendingMeta?.type) {
      // Metadata emitted by NexKit itself (`# type: enum · one of: a | b · default: "a"`)
      // round-trips losslessly.
      field = { key, type: pendingMeta.type };
      if (pendingMeta.values) field.values = pendingMeta.values;
      if (pendingMeta.default !== undefined) field.default = pendingMeta.default;
      if (pendingMeta.optional) field.optional = true;
    } else {
      field = inferField(key, value);
      if (commentedOut) field.optional = true;
    }
    if (pendingComment) field.description = pendingComment;
    fields.push(field);
    pendingComment = undefined;
    pendingMeta = undefined;
  };

  for (const rawLine of dotenv.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) {
      pendingComment = undefined;
      pendingMeta = undefined;
      continue;
    }
    if (line.startsWith("#")) {
      const text = line.replace(/^#\s?/, "");
      const meta = parseMetaLine(text);
      if (meta) {
        pendingMeta = meta;
        continue;
      }
      // Commented-out assignments (`# PORT=3000`) are treated as optional vars.
      const commented = /^([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/.exec(text);
      if (commented) push(commented[1]!, unquote(commented[2]!), true);
      else if (!/^Generated by/i.test(text)) pendingComment = text;
      continue;
    }
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    push(match[1]!, unquote(match[2]!), false);
  }
  return fields;
}

const FIELD_TYPES = new Set(["string", "number", "port", "boolean", "url", "enum", "list"]);

/** Parses `type: enum · one of: a | b · default: "a" · optional` lines written by {@link renderEnvExample}. */
function parseMetaLine(text: string): Partial<EnvFieldSpec> | undefined {
  if (!/^type:\s*/.test(text)) return undefined;
  const meta: Partial<EnvFieldSpec> = {};
  for (const part of text.split("·").map((p) => p.trim())) {
    const typeMatch = /^type:\s*(\w+)$/.exec(part);
    const valuesMatch = /^one of:\s*(.+)$/.exec(part);
    const defaultMatch = /^default:\s*(.+)$/.exec(part);
    if (typeMatch && FIELD_TYPES.has(typeMatch[1]!))
      meta.type = typeMatch[1] as EnvFieldSpec["type"];
    else if (valuesMatch) meta.values = valuesMatch[1]!.split("|").map((v) => v.trim());
    else if (defaultMatch) {
      try {
        meta.default = JSON.parse(defaultMatch[1]!) as NonNullable<EnvFieldSpec["default"]>;
      } catch {
        meta.default = defaultMatch[1]!;
      }
    } else if (part === "optional") meta.optional = true;
  }
  return meta.type ? meta : undefined;
}

function unquote(value: string): string {
  const trimmed = value.replace(/\s+#.*$/, "").trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function inferField(key: string, value: string): EnvFieldSpec {
  const secret = SECRET_KEY.test(key);
  const isPlaceholder =
    value === "" || /^<.*>$/.test(value) || /^(change|replace|your|xxx)/i.test(value);
  const spec: EnvFieldSpec = { key, type: "string" };

  if (/^PORT$|_PORT$/.test(key)) spec.type = "port";
  else if (
    /_(URL|URI)$/.test(key) ||
    /^(https?|postgres(ql)?|mysql|redis|mongodb(\+srv)?|amqp):\/\//.test(value)
  )
    spec.type = "url";
  else if (
    /^(true|false|yes|no|on|off|1|0)$/i.test(value) &&
    /^(ENABLE|DISABLE|IS_|HAS_|USE_|DEBUG|FEATURE)/i.test(key)
  )
    spec.type = "boolean";
  else if (/^(true|false)$/i.test(value)) spec.type = "boolean";
  else if (value !== "" && !Number.isNaN(Number(value)) && !secret) spec.type = "number";
  else if (key === "NODE_ENV") {
    spec.type = "enum";
    spec.values = ["development", "test", "production"];
  } else if (key === "LOG_LEVEL") {
    spec.type = "enum";
    spec.values = ["trace", "debug", "info", "warn", "error", "fatal", "silent"];
  } else if (value.includes(",") && !value.includes("://")) spec.type = "list";

  if (!secret && !isPlaceholder) {
    if (spec.type === "number" || spec.type === "port") spec.default = Number(value);
    else if (spec.type === "boolean") spec.default = /^(true|yes|on|1)$/i.test(value);
    else if (spec.type === "list")
      spec.default = value
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean);
    else if (spec.type !== "url") spec.default = value;
  }
  if (secret && isPlaceholder) delete spec.default;
  return spec;
}

function literal(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((v) => JSON.stringify(v)).join(", ")}]`;
  return JSON.stringify(value);
}

function renderField(field: EnvFieldSpec): string {
  const parts: string[] = [`type: ${literal(field.type)}`];
  if (field.type === "enum") parts.push(`values: ${literal(field.values ?? [])}`);
  if (field.default !== undefined) parts.push(`default: ${literal(field.default)}`);
  if (field.optional && field.default === undefined) parts.push("optional: true");
  if (field.description) parts.push(`description: ${literal(field.description)}`);
  // Keep output Prettier-stable (printWidth 100): expand long entries.
  const inline = `  ${field.key}: { ${parts.join(", ")} },`;
  if (inline.length <= 100) return inline;
  return `  ${field.key}: {\n${parts.map((p) => `    ${p},`).join("\n")}\n  },`;
}

/** Renders `src/config/env.ts`. */
export function renderEnvConfig(fields: EnvFieldSpec[] = DEFAULT_ENV_FIELDS): string {
  return `// Generated by \`nexkit generate config\`. Edit freely — this file is yours.
//
// Validates environment variables once at startup and exports a typed, frozen
// object. Invalid configuration throws an EnvValidationError listing every
// problem (variable names and reasons only — never values).
import { defineEnvSchema, validateEnv, type InferEnv } from "@nexkitjs/config";

export const envSchema = defineEnvSchema({
${fields.map(renderField).join("\n")}
});

export type Env = InferEnv<typeof envSchema>;

export const env: Env = validateEnv(envSchema);
`;
}

/** Renders a `.env.example` from field specs. */
export function renderEnvExample(fields: EnvFieldSpec[] = DEFAULT_ENV_FIELDS): string {
  const lines = ["# Generated by NexKit. Copy to .env and fill in the values.", ""];
  for (const f of fields) {
    if (f.description) lines.push(`# ${f.description}`);
    const meta = [`# type: ${f.type}`];
    if (f.type === "enum") meta.push(`one of: ${(f.values ?? []).join(" | ")}`);
    if (f.default !== undefined) meta.push(`default: ${literal(f.default)}`);
    if (f.optional) meta.push("optional");
    lines.push(meta.join(" · "));
    const secret = SECRET_KEY.test(f.key);
    const value = secret
      ? "<secret>"
      : f.default !== undefined
        ? Array.isArray(f.default)
          ? f.default.join(",")
          : String(f.default)
        : "";
    const assignment = `${f.key}=${value}`;
    lines.push(f.optional || f.default !== undefined ? `# ${assignment}` : assignment);
    lines.push("");
  }
  return lines.join("\n");
}

const RATELIMIT_IMPORT = `import {
  MemoryRateLimitStore,
  createFixedWindowLimiter,
  type RateLimiter,
} from "@nexkitjs/ratelimit";
`;

export interface MiddlewareTemplateOptions {
  framework: Exclude<Framework, "none">;
  /** Include health routes. Defaults to true. */
  health?: boolean;
  /** Include rate limiting. Defaults to true. */
  rateLimit?: boolean;
}

/** Renders `src/nexkit.ts` for Express or Fastify. */
export function renderMiddleware(options: MiddlewareTemplateOptions): string {
  return options.framework === "express"
    ? renderExpressMiddleware(options)
    : renderFastifyMiddleware(options);
}

function renderExpressMiddleware(o: MiddlewareTemplateOptions): string {
  const health = o.health ?? true;
  const rateLimit = o.rateLimit ?? true;
  return `// Generated by \`nexkit generate middleware --framework express\`. Edit freely — this file is yours.
//
// Wires NexKit into an Express app in two steps: \`before(app)\` mounts request
// context, secure headers, size limits${health ? ", health routes" : ""}${rateLimit ? " and rate limiting" : ""};
// \`after(app)\` mounts the 404 and error handlers. Everything in between is yours.
import type { Express } from "express";
import {
  errorHandler,
${health ? "  healthRoutes,\n" : ""}  notFoundHandler,
${rateLimit ? "  rateLimit,\n" : ""}  requestContext,
  requestSizeLimit,
  secureHeaders,
} from "@nexkitjs/express";
${health ? 'import { createHealthRegistry, type HealthRegistry } from "@nexkitjs/health";\n' : ""}import { createLogger, type Logger } from "@nexkitjs/logger";
${rateLimit ? RATELIMIT_IMPORT : ""}
export interface NexkitOptions {
  logger?: Logger;
${health ? "  health?: HealthRegistry;\n" : ""}${rateLimit ? "  rateLimiter?: RateLimiter;\n" : ""}  /** Max request body size accepted before parsing. Defaults to "1mb". */
  bodyLimit?: string;
  /** Enables HSTS and JSON logs. Defaults to NODE_ENV === "production". */
  isProduction?: boolean;
}

export interface Nexkit {
  logger: Logger;
${health ? "  health: HealthRegistry;\n" : ""}  /** Mount before your routes. */
  before(app: Express): void;
  /** Mount after your routes. */
  after(app: Express): void;
}

export function createNexkit(options: NexkitOptions = {}): Nexkit {
  const isProduction = options.isProduction ?? process.env.NODE_ENV === "production";
  const logger =
    options.logger ?? createLogger({ name: "app", transport: isProduction ? "json" : "pretty" });
${health ? "  const health = options.health ?? createHealthRegistry();\n" : ""}${
    rateLimit
      ? `  // NOTE: the memory store is single-process. For multiple instances pass a
  // Redis-backed limiter via \`options.rateLimiter\` (see @nexkitjs/ratelimit docs).
  const rateLimiter =
    options.rateLimiter ??
    createFixedWindowLimiter({ store: new MemoryRateLimitStore(), limit: 100, windowMs: 60_000 });
`
      : ""
  }
  return {
    logger,
${health ? "    health,\n" : ""}    before(app) {
      app.disable("x-powered-by");
      app.use(requestContext({ logger${health ? ', ignore: ["/health/live", "/health/ready"]' : ""} }));
      app.use(secureHeaders({ strictTransportSecurity: isProduction ? {} : false }));
      app.use(requestSizeLimit({ maxBytes: options.bodyLimit ?? "1mb" }));
${health ? "      app.use(healthRoutes(health));\n" : ""}${rateLimit ? "      app.use(rateLimit({ limiter: rateLimiter }));\n" : ""}    },
    after(app) {
      app.use(notFoundHandler());
      app.use(errorHandler({ logger }));
    },
  };
}
`;
}

function renderFastifyMiddleware(o: MiddlewareTemplateOptions): string {
  const health = o.health ?? true;
  const rateLimit = o.rateLimit ?? true;
  return `// Generated by \`nexkit generate middleware --framework fastify\`. Edit freely — this file is yours.
//
// Registers the NexKit Fastify plugin with sensible defaults: request context,
// secure headers${health ? ", health routes" : ""}${rateLimit ? ", rate limiting" : ""}, error and 404 handlers.
import type { FastifyInstance } from "fastify";
import { nexkit, requestIdGenerator } from "@nexkitjs/fastify";
${health ? 'import { createHealthRegistry, type HealthRegistry } from "@nexkitjs/health";\n' : ""}import { createLogger, type Logger } from "@nexkitjs/logger";
${rateLimit ? RATELIMIT_IMPORT : ""}
export interface NexkitOptions {
  logger?: Logger;
${health ? "  health?: HealthRegistry;\n" : ""}${rateLimit ? "  rateLimiter?: RateLimiter;\n" : ""}  /** Enables HSTS and JSON logs. Defaults to NODE_ENV === "production". */
  isProduction?: boolean;
}

export interface Nexkit {
  logger: Logger;
${health ? "  health: HealthRegistry;\n" : ""}  /** Pass to the Fastify factory so request ids honour trusted X-Request-Id headers. */
  genReqId: ReturnType<typeof requestIdGenerator>;
  /** Registers the plugin. Call before defining routes. */
  register(app: FastifyInstance): Promise<void>;
}

export function createNexkit(options: NexkitOptions = {}): Nexkit {
  const isProduction = options.isProduction ?? process.env.NODE_ENV === "production";
  const logger =
    options.logger ?? createLogger({ name: "app", transport: isProduction ? "json" : "pretty" });
${health ? "  const health = options.health ?? createHealthRegistry();\n" : ""}${
    rateLimit
      ? `  // NOTE: the memory store is single-process. For multiple instances pass a
  // Redis-backed limiter via \`options.rateLimiter\` (see @nexkitjs/ratelimit docs).
  const rateLimiter =
    options.rateLimiter ??
    createFixedWindowLimiter({ store: new MemoryRateLimitStore(), limit: 100, windowMs: 60_000 });
`
      : ""
  }
  return {
    logger,
${health ? "    health,\n" : ""}    genReqId: requestIdGenerator(),
    async register(app) {
      await app.register(nexkit, {
        logger,
${health ? "        health,\n" : ""}${rateLimit ? "        rateLimit: { limiter: rateLimiter },\n" : ""}        secureHeaders: { strictTransportSecurity: isProduction ? {} : false },
${health ? '        requestContext: { ignore: ["/health/live", "/health/ready"] },\n' : ""}      });
    },
  };
}
`;
}

/** Packages required by the generated files. */
export function requiredPackages(
  framework: Framework,
  options: { health?: boolean; rateLimit?: boolean } = {},
): string[] {
  const pkgs = ["@nexkitjs/config", "@nexkitjs/logger"];
  if (framework !== "none") {
    pkgs.push(`@nexkitjs/${framework}`);
    if (options.health ?? true) pkgs.push("@nexkitjs/health");
    if (options.rateLimit ?? true) pkgs.push("@nexkitjs/ratelimit");
  }
  return pkgs;
}
